CREATE TABLE `enroll_matched_TESDA_tbl` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `match_id` int unsigned DEFAULT NULL,
  `enrollment_id` int unsigned NOT NULL,
  `tuloy_id` varchar(50) DEFAULT NULL COMMENT 'Unique id across agency pre-generated from TULOY',
  `member_id` int unsigned NOT NULL COMMENT 'Entry_id',
  `uli_id` varchar(50) DEFAULT NULL COMMENT 'TESDA ULI',
  `mm_first_name` varchar(100) DEFAULT NULL,
  `mm_middle_name` varchar(100) DEFAULT NULL,
  `mm_last_name` varchar(100) DEFAULT NULL,
  `diploma` json DEFAULT NULL COMMENT 'JSON object containing: program_name, date_enrolled, program_duration, academic_year, year_level, semester, enrollment_status, date_encoded, date_updated',
  `short_course` json DEFAULT NULL COMMENT 'JSON object containing: program_name, start_date, end_date, training_status, date_encoded, date_updated',
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  `agency_id` int unsigned NOT NULL DEFAULT '2',
  `has_diploma` tinyint(1) GENERATED ALWAYS AS ((`diploma` is not null)) VIRTUAL,
  `has_short_course` tinyint(1) GENERATED ALWAYS AS ((`short_course` is not null)) VIRTUAL,
  PRIMARY KEY (`id`),
  KEY `fk_tesda_matched_enrollment` (`enrollment_id`),
  KEY `fk_tesda_matched_transaction` (`match_id`),
  KEY `idx_enroll_tesda_tuloy` (`tuloy_id`,`agency_id`,`match_id`,`member_id`),
  KEY `idx_has_diploma` (`has_diploma`),
  KEY `idx_has_short_course` (`has_short_course`),
  CONSTRAINT `fk_tesda_matched_transaction` FOREIGN KEY (`match_id`) REFERENCES `matching_transaction_TESDA_tbl` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB AUTO_INCREMENT=191 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
