CREATE TABLE `bcmd_batch_export` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `batch_id` bigint unsigned NOT NULL,
  `export_no` int unsigned NOT NULL,
  `file_type` varchar(8) NOT NULL DEFAULT 'DETAIL',
  `status` varchar(9) NOT NULL,
  `generator_version` varchar(24) NOT NULL,
  `serialization_version` varchar(24) NOT NULL,
  `header_set_sha256` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `sha256` char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `byte_count` bigint unsigned DEFAULT NULL,
  `row_count` int unsigned DEFAULT NULL,
  `idempotency_key` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `request_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `created_by_api_user_id` int DEFAULT NULL,
  `created_by_staff_user_id` bigint unsigned DEFAULT NULL,
  `created_by_agency` varchar(16) NOT NULL,
  `request_id` varchar(64) NOT NULL,
  `failure_code` varchar(32) DEFAULT NULL,
  `started_at` timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `completed_at` timestamp(3) NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_bcmd_export_no` (`batch_id`,`export_no`),
  UNIQUE KEY `uq_bcmd_export_idem` (`batch_id`,`created_by_api_user_id`,`idempotency_key`),
  UNIQUE KEY `uq_bcmd_export_staff_idem` (`batch_id`,`created_by_staff_user_id`,`idempotency_key`),
  KEY `ix_bcmd_export_reap` (`status`,`started_at`),
  KEY `fk_bcmd_export_creator` (`created_by_api_user_id`),
  KEY `fk_bcmd_export_staff_creator` (`created_by_staff_user_id`),
  CONSTRAINT `fk_bcmd_export_batch` FOREIGN KEY (`batch_id`) REFERENCES `bcmd_batch` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_bcmd_export_creator` FOREIGN KEY (`created_by_api_user_id`) REFERENCES `api_users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_bcmd_export_staff_creator` FOREIGN KEY (`created_by_staff_user_id`) REFERENCES `staff_users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `ck_bcmd_export_creator_identity` CHECK ((((`created_by_api_user_id` is not null) + (`created_by_staff_user_id` is not null)) = 1)),
  CONSTRAINT `ck_bcmd_export_done` CHECK (((`status` = _utf8mb4'COMPLETED') = ((`sha256` is not null) and (`byte_count` is not null) and (`row_count` is not null) and (`completed_at` is not null)))),
  CONSTRAINT `ck_bcmd_export_file` CHECK ((`file_type` = _utf8mb4'DETAIL')),
  CONSTRAINT `ck_bcmd_export_status` CHECK ((`status` in (_utf8mb4'STARTED',_utf8mb4'COMPLETED',_utf8mb4'FAILED',_utf8mb4'ABORTED')))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
