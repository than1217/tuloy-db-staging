CREATE TABLE `lib_psgc_barangay` (
  `barangay_id` int unsigned NOT NULL AUTO_INCREMENT COMMENT 'Barangay ID',
  `name` varchar(125) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL COMMENT 'Name',
  `code` varchar(30) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci DEFAULT NULL COMMENT 'Code',
  `geocode` char(9) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci DEFAULT '' COMMENT 'Geocode',
  `psa_code` char(10) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL COMMENT 'PSA Code',
  `is_gida` enum('No','Yes') CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL DEFAULT 'No' COMMENT 'Is GIDA',
  `city_id` int unsigned NOT NULL COMMENT 'Foreign Key of City/Municipality',
  `dt_inserted` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Date/Time Inserted',
  `inserted_by` int unsigned DEFAULT NULL COMMENT 'Inserted By',
  `dt_updated` datetime DEFAULT NULL COMMENT 'Date/Time Updated',
  `last_updated_by` int unsigned DEFAULT NULL COMMENT 'Last Updated By',
  `archived` tinyint unsigned NOT NULL DEFAULT '0' COMMENT 'Archived',
  `dt_archived` datetime DEFAULT NULL COMMENT 'Date/Time Last Archived',
  `last_archived_by` int unsigned DEFAULT NULL COMMENT 'Last Archived By',
  `dt_restored` datetime DEFAULT NULL COMMENT 'Date/Time Last Restored',
  `last_restored_by` int unsigned DEFAULT NULL COMMENT 'Last Restored By',
  `dt_last_modified` datetime DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT 'Date/Time Last Modified',
  `urban_rural` char(5) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci DEFAULT NULL,
  PRIMARY KEY (`barangay_id`),
  KEY `municipality_city_idx` (`city_id`) USING BTREE,
  KEY `inserted_by` (`inserted_by`) USING BTREE,
  KEY `last_updated_by` (`last_updated_by`) USING BTREE,
  KEY `last_archived_by` (`last_archived_by`) USING BTREE,
  KEY `last_restored_by` (`last_restored_by`) USING BTREE,
  FULLTEXT KEY `fulltext_barangay` (`name`,`code`,`geocode`,`psa_code`),
  CONSTRAINT `lib_psgc_barangay_ibfk_1` FOREIGN KEY (`city_id`) REFERENCES `lib_psgc_city` (`city_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `lib_psgc_barangay_ibfk_2` FOREIGN KEY (`inserted_by`) REFERENCES `_user` (`user_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `lib_psgc_barangay_ibfk_3` FOREIGN KEY (`last_updated_by`) REFERENCES `_user` (`user_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `lib_psgc_barangay_ibfk_4` FOREIGN KEY (`last_archived_by`) REFERENCES `_user` (`user_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `lib_psgc_barangay_ibfk_5` FOREIGN KEY (`last_restored_by`) REFERENCES `_user` (`user_id`) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci ROW_FORMAT=DYNAMIC COMMENT='Library of PSGC Barangay';
