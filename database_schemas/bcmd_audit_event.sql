CREATE TABLE `bcmd_audit_event` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `occurred_at` timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `event_type` varchar(24) NOT NULL,
  `batch_id` bigint unsigned DEFAULT NULL,
  `export_id` bigint unsigned DEFAULT NULL,
  `parent_event_id` bigint unsigned DEFAULT NULL,
  `actor_api_user_id` int DEFAULT NULL,
  `actor_staff_user_id` bigint unsigned DEFAULT NULL,
  `actor_label` varchar(64) DEFAULT NULL,
  `actor_agency` varchar(16) DEFAULT NULL,
  `request_id` varchar(64) NOT NULL,
  `client_ip` varchar(45) DEFAULT NULL,
  `reason_code` varchar(32) DEFAULT NULL,
  `sha256` char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_bcmd_audit_result` (`parent_event_id`),
  KEY `ix_bcmd_audit_batch` (`batch_id`,`id`),
  KEY `ix_bcmd_audit_pending` (`event_type`,`occurred_at`),
  KEY `fk_bcmd_audit_export` (`export_id`),
  KEY `fk_bcmd_audit_actor` (`actor_api_user_id`),
  KEY `fk_bcmd_audit_staff_actor` (`actor_staff_user_id`),
  CONSTRAINT `fk_bcmd_audit_actor` FOREIGN KEY (`actor_api_user_id`) REFERENCES `api_users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_bcmd_audit_batch` FOREIGN KEY (`batch_id`) REFERENCES `bcmd_batch` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_bcmd_audit_export` FOREIGN KEY (`export_id`) REFERENCES `bcmd_batch_export` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_bcmd_audit_parent` FOREIGN KEY (`parent_event_id`) REFERENCES `bcmd_audit_event` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_bcmd_audit_staff_actor` FOREIGN KEY (`actor_staff_user_id`) REFERENCES `staff_users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `ck_bcmd_audit_actor` CHECK ((((`actor_api_user_id` is null) or (`actor_staff_user_id` is null)) and ((`actor_api_user_id` is not null) or (`actor_staff_user_id` is not null) or (`actor_label` is not null)))),
  CONSTRAINT `ck_bcmd_audit_type` CHECK ((`event_type` in (_utf8mb4'BATCH_CREATED',_utf8mb4'DQA_COMPLETED',_utf8mb4'EXPORT_STARTED',_utf8mb4'EXPORT_COMPLETED',_utf8mb4'EXPORT_FAILED',_utf8mb4'EXPORT_ABORTED',_utf8mb4'DOWNLOAD_ADMITTED',_utf8mb4'DOWNLOAD_COMPLETED',_utf8mb4'DOWNLOAD_FAILED',_utf8mb4'DOWNLOAD_UNCERTAIN',_utf8mb4'ACCESS_DENIED',_utf8mb4'TAMPER_DETECTED',_utf8mb4'BATCH_PURGED')))
) ENGINE=InnoDB AUTO_INCREMENT=9 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
