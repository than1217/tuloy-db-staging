  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `batch_id` bigint unsigned NOT NULL,
  `line_no` int unsigned NOT NULL,
  `tuloy_id` varchar(50) NOT NULL,
  `academic_year` varchar(20) NOT NULL DEFAULT '',
  `semester` int NOT NULL DEFAULT '0',
  `source_record_id` int unsigned NOT NULL,
  `entitlement_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `dqa_status` varchar(5) NOT NULL,
  `region_name` varchar(150) DEFAULT NULL,
  `region_psgc` varchar(12) DEFAULT NULL,
  `province_name` varchar(150) DEFAULT NULL,
  `province_psgc` varchar(12) DEFAULT NULL,
  `municipality_name` varchar(150) DEFAULT NULL,
  `municipality_psgc` varchar(12) DEFAULT NULL,
  `barangay_name` varchar(150) DEFAULT NULL,
  `barangay_psgc` varchar(12) DEFAULT NULL,
