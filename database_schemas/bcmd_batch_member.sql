  `ip_indicator` varchar(3) DEFAULT NULL,
  `date_of_birth_raw` varchar(32) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_bcmd_member_batch_id` (`batch_id`,`id`),
  UNIQUE KEY `uq_bcmd_member_line` (`batch_id`,`line_no`),
  UNIQUE KEY `uq_bcmd_member_entitlement` (`batch_id`,`entitlement_hash`),
  KEY `ix_bcmd_member_dqa` (`batch_id`,`dqa_status`,`line_no`),
