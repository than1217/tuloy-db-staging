CREATE TABLE `tbl_person` (
  `person_id` int unsigned NOT NULL AUTO_INCREMENT COMMENT 'Primary Key of Person Table',
  `first_name` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL COMMENT 'First Name',
  `middle_name` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci DEFAULT NULL COMMENT 'Middle Name',
  `last_name` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci DEFAULT NULL COMMENT 'Last Name',
  `ext_name_id` int unsigned DEFAULT NULL COMMENT 'Extended Name',
  `date_of_birth` date DEFAULT NULL COMMENT 'Date of Birth',
  `sex_id` int unsigned NOT NULL COMMENT 'Foreign Key of Sex Library',
  `civil_status_id` int unsigned NOT NULL COMMENT 'Foreign Key to Civil Status',
  `phil_id` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci DEFAULT NULL COMMENT 'PhilSys Card Number. The PCN which is the public version of PSN shall be used for physical or online transactions.',
  `attending_school` tinyint unsigned DEFAULT NULL COMMENT 'If beneficiary is attending school',
  `educ_facility_id` int unsigned DEFAULT NULL COMMENT 'Foreign Key from Educational Facility Table. School currently attending.',
  `grade_level_id` int unsigned DEFAULT NULL COMMENT 'Foreign Key from Grade Level Library. Designates the present educational level.',
  `is_pregnant` int unsigned DEFAULT NULL COMMENT 'Foreign key from lib_pregnancy_status',
  `health_facility_id` int unsigned DEFAULT NULL,
  `occupation_id` int unsigned DEFAULT NULL COMMENT 'Foreign Key of Occupation',
  `ip_group_id` int unsigned DEFAULT NULL,
  `lrn` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci DEFAULT NULL COMMENT 'Learner reference number assigned to each student by DepEd',
  `photo_src` varchar(250) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci DEFAULT 'person_avatar.png' COMMENT 'Location of the Avatar of Person',
  `roster_id` int unsigned DEFAULT NULL,
  `dt_inserted` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Date and Time the record was inserted',
  `dt_updated` datetime DEFAULT NULL COMMENT 'Date and Time the records was last updated',
  `archived` tinyint unsigned NOT NULL DEFAULT '0' COMMENT 'State if record was archived or deleted. (0-False; 1-True)',
  `dt_archived` datetime DEFAULT NULL COMMENT 'Date and Time the record was archived. Reference date for physical archiving of records. Set to NULL on default or after record was restored.',
  `child_grantee` tinyint NOT NULL DEFAULT '0',
  `newmember_id` varchar(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci DEFAULT NULL,
  `mcct_person_id` int DEFAULT NULL,
  `validation_num` varchar(200) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci DEFAULT NULL COMMENT 'Proof of validation for false duplicates to enter the system',
  `match_key` binary(16) GENERATED ALWAYS AS (unhex(md5(concat_ws(_utf8mb4'/',upper(trim(regexp_replace(`first_name`,_utf8mb4'\\s+',_utf8mb4' '))),upper(trim(regexp_replace(`last_name`,_utf8mb4'\\s+',_utf8mb4' '))),`date_of_birth`)))) VIRTUAL,
  PRIMARY KEY (`person_id`) USING BTREE,
  KEY `civ_stat_id` (`civil_status_id`) USING BTREE,
  KEY `date_of_birth` (`date_of_birth`) USING BTREE,
  KEY `dt_updated` (`dt_updated`) USING BTREE,
  KEY `first_name_2` (`first_name`) USING BTREE,
  KEY `grade_level_id` (`grade_level_id`) USING BTREE,
  KEY `health_facility_id` (`health_facility_id`) USING BTREE,
  KEY `ip_group_id` (`ip_group_id`) USING BTREE,
  KEY `is_pregnant` (`is_pregnant`) USING BTREE,
  KEY `middle_name` (`middle_name`) USING BTREE,
  KEY `occupation_id` (`occupation_id`) USING BTREE,
  KEY `roster_id` (`roster_id`) USING BTREE,
  KEY `sex_id` (`sex_id`) USING BTREE,
  KEY `validation_num` (`validation_num`) USING BTREE,
  KEY `idx_person_lookup` (`last_name`,`first_name`,`middle_name`,`person_id`) USING BTREE,
  KEY `idx_newmember_covering` (`newmember_id`,`person_id`,`first_name`,`middle_name`,`last_name`,`date_of_birth`,`sex_id`,`ext_name_id`,`is_pregnant`,`child_grantee`,`archived`) USING BTREE,
  KEY `idx_archived` (`archived`) USING BTREE,
  KEY `idx_person_match_key` (`match_key`),
  FULLTEXT KEY `first_name` (`first_name`,`middle_name`,`last_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci ROW_FORMAT=DYNAMIC COMMENT='Table of Person';
